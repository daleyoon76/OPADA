# 절 표지: 이 단어가 나오는 위치를 앵커로 삼는다.
SECTION_ANCHOR_RE = re.compile(r"제출\s*서류|구비\s*서류|필요\s*서류|지참\s*서류")

# 앵커 뒤 이 길이(문자수)까지만 어휘 매칭 대상으로 본다. 너무 좁으면 표 형태 서류 목록을
# 놓치고, 너무 넓으면 본문의 다른 절까지 삼킨다. 표본 관찰상 800자면 대부분의 목록을 덮는다.
WINDOW_CHARS = 800


def extract_submission_docs(text: str) -> list[str]:
    """제출서류/구비서류 절 근처에서 닫힌 어휘로 서류명을 뽑는다. 못 찾으면 빈 리스트."""
    names: list[str] = []
    seen: set[str] = set()
    for anchor in SECTION_ANCHOR_RE.finditer(text):
        window = text[anchor.end() : anchor.end() + WINDOW_CHARS]
        masked = window
        for label, pattern in DOC_NAME_PATTERNS:
            for match in re.finditer(pattern, masked):
                name = label or re.sub(r"\s+", "", match.group(0))
                if name and name not in seen:
                    seen.add(name)
                    names.append(name)
                masked = masked[: match.start()] + ("\x00" * (match.end() - match.start())) + masked[match.end() :]
    return names
